/**
 * 16進数の色（CSS の `<hex-color>`。`#2f6fde`・`#fff` など）
 * 型で確かめるのは `#` で始まることだけで、桁数や文字は確かめない
 */
export type HexColor = `#${string}`;

/**
 * 色の関数で書いた色のうち、具体的な色を表すもの（`rgb()`・`hsl()`・`oklch()` など）
 * 型で確かめるのは関数の名前だけで、引数は確かめない
 */
export type FunctionalColor =
  | `rgb(${string})`
  | `rgba(${string})`
  | `hsl(${string})`
  | `hsla(${string})`
  | `hwb(${string})`
  | `lab(${string})`
  | `lch(${string})`
  | `oklab(${string})`
  | `oklch(${string})`
  | `color(${string})`;

/**
 * 具体的な色の値（CSS Color Module Level 4 の absolute color）
 * 16進数の色・色の関数・色の名前を受け付ける。JavaScript で色を計算するものが受け取る型
 * CSS の変数（`var()`）・`currentColor`・`inherit` など、描くときまで決まらない値は受け付けない
 * 型で確かめるのは書き方だけで、中身（`'#zzz'` や、`rgb(from …)` のような相対的な色）は確かめない
 */
export type AbsoluteColor = HexColor | FunctionalColor | NamedColor;
